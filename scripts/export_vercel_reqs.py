"""Export runtime dependencies from backend/pyproject.toml to root requirements.txt."""

import os
import sys
import tomllib


def main() -> None:
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    pyproject_path = os.path.join(repo_root, "backend", "pyproject.toml")
    reqs_path = os.path.join(repo_root, "requirements.txt")

    if not os.path.exists(pyproject_path):
        print(f"Error: {pyproject_path} not found.", file=sys.stderr)
        sys.exit(1)

    with open(pyproject_path, "rb") as f:
        data = tomllib.load(f)

    deps = data.get("project", {}).get("dependencies", [])
    if not deps:
        print("Error: No runtime dependencies found in pyproject.toml.", file=sys.stderr)
        sys.exit(1)

    header = (
        "# Auto-generated by scripts/export_vercel_reqs.py (make vercel-reqs)\n"
        "# Runtime dependencies for Vercel deployment — DO NOT EDIT MANUALLY\n"
    )
    expected_content = header + "\n".join(deps) + "\n"

    if "--check" in sys.argv:
        if not os.path.exists(reqs_path):
            print("Error: requirements.txt does not exist.", file=sys.stderr)
            sys.exit(1)
        with open(reqs_path, "r", encoding="utf-8") as f:
            current = f.read()
        if current.strip() != expected_content.strip():
            print(
                "Error: root requirements.txt is out of sync with backend/pyproject.toml!\n"
                "Run 'make vercel-reqs' to regenerate.",
                file=sys.stderr,
            )
            sys.exit(1)
        print("requirements.txt is in sync with backend/pyproject.toml.")
        return

    with open(reqs_path, "w", encoding="utf-8") as f:
        f.write(expected_content)

    print(f"Exported {len(deps)} runtime dependencies to {reqs_path}")


if __name__ == "__main__":
    main()
